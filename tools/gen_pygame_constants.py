"""Generate a pure-python pygame.constants stand-in from the local pygame-ce install."""
import pathlib

import pygame
import pygame.constants

out = pathlib.Path("shardlight/core/pygame_constants.py")
names = []
values = {}
for key, val in vars(pygame.constants).items():
    if key.startswith("__"):
        continue
    if isinstance(val, (int, float, str, bool)):
        names.append(key)
        values[key] = val
names.sort()

all_list = getattr(pygame.constants, "__all__", None)
lines = [
    '"""A pure-python stand-in for ``pygame.constants``.',
    "",
    "The wasm build of pygame-ce on the pygame-web CDN is missing ``pygame/constants.py``,",
    "so ``import pygame`` dies with ``No module named 'pygame.constants'``.  The browser",
    "build registers this module under that name before pygame is imported.",
    "",
    "Generated by tools/gen_pygame_constants.py; do not edit by hand.",
    '"""',
    "from __future__ import annotations",
    "",
]
for key in names:
    lines.append(f"{key} = {values[key]!r}")
lines.append("")
if all_list:
    lines.append("__all__ = [")
    for key in all_list:
        if key in values:
            lines.append(f"    {key!r},")
    lines.append("]")
else:
    lines.append("__all__ = [")
    for key in names:
        lines.append(f"    {key!r},")
    lines.append("]")
lines.append("")
out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {out} with {len(names)} constants ({out.stat().st_size // 1024} KB)")
